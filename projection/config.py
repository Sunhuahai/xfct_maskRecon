"""
config.py

共享参数配置文件

功能: 定义所有成像参数和物理常数，便于统一修改

==============================================================================
探测器参数
==============================================================================
l_d         - 探测器像素间距 (mm)
n_dx, n_dz  - 探测器阵列尺寸 (像素数)
a, b        - 几何位置参数 (mm)
d_pin       - 针孔直径 (mm)
disDec      - 源-物距 (mm)

==============================================================================
成像参数
==============================================================================
theta_step  - 旋转角度步进 (度)
n_angles    - 角度数量
e_min, e_max, e_bins - 能量分箱参数 (用于散射成像)

==============================================================================
衰减计算参数
==============================================================================
num_segments - 衰减路径分段数 (精度vs速度权衡)

==============================================================================
物理常数
==============================================================================
electron_rest_energy - 电子静止能量 (keV)

==============================================================================
"""

import numpy as np

# ========================================================================
# 第一部分: 探测器几何参数
# ========================================================================

# 探测器像素间距 (mm)
L_D = 0.25

# 探测器阵列尺寸 (像素数)
# 注意: 这里是重建投影网格，不应直接按 Geant4 的 virtual detector voxels_x 对齐
N_DX = 80  # x方向像素数
N_DZ = 80  # z方向像素数

# 几何位置参数 (mm)
# L_DP: 探测器到针孔的距离 (方向为-y)
# L_CP: 旋转中心到针孔的距离 (沿+y)
L_DP = 30
L_CP = 50

# 针孔直径 (mm)
D_PIN = 0.5

# 源-物距 (Source-to-Object Distance, mm)
# 应与 Geant4 的 scan.source_radius_mm 保持一致
DIS_DEC = 300

# X 射线源在两个正交方向上的半角 (deg)
# 用于把能谱文件归一化到实验束流条件；
# 应与 Geant4 的 scan.cone_half_angle_deg 保持一致。
XRAY_SPECTRUM_THETA_DEG = 4.0
XRAY_SPECTRUM_PHI_DEG = 4.0

# ========================================================================
# 第二部分: 成像系统参数
# ========================================================================

# 旋转角度步进 (度)
# 旋转范围: 0 : theta_step : 44*theta_step
THETA_STEP = 8

# 角度数量
N_ANGLES = 45

# 能量分箱参数 (用于散射成像)
E_MIN = 1  # 最小能量 (keV)
E_MAX = 150  # 最大能量 (keV)
E_BINS = 150  # 能量分箱数

# ========================================================================
# 第三部分: 衰减计算参数
# ========================================================================

# 衰减路径分段数
# 用于数值积分计算光子从散射点到探测器的衰减
# 值越大精度越高，但计算越慢
NUM_SEGMENTS = 100

# ========================================================================
# 第四部分: 物理常数
# ========================================================================

# 电子静止能量 (keV)
ELECTRON_REST_ENERGY = 511

# ========================================================================
# 第五部分: 输出文件名模板
# ========================================================================

# 输出目录
OUTPUT_DIR = "projections"

# ========================================================================
# 第六部分: Phantom参数
# ========================================================================

# Phantom参数
# 当前默认与 geant4_simulation/config/pmma_1.yaml 对齐
PHANTOM_SIZE = np.array([120, 120, 80])  # x, y, z方向体素数
VOXEL_SIZE = 0.25  # 体素大小 (mm)

# Phantom索引偏移 (mm)
# 这里不是 Geant4 世界坐标中的中心位置，而是把重建坐标映射回
# phantom 体素索引时使用的半尺寸偏移。
PHANTOM_OFFSET_X = 15
PHANTOM_OFFSET_Y = 15
PHANTOM_OFFSET_Z = 10

# ========================================================================
# 第七部分: GEANT4坐标映射参数
# ========================================================================

# 将GEANT4原始坐标映射到重建坐标系时的平移与轴翻转参数
#
# 映射公式（在各主脚本中使用）:
#   x0 = x_raw + X_SHIFT_MM
#   y0 = y_raw * Y_SIGN + Y_SHIFT_MM + y_oc
#   z0 = z_raw
#
# 参数物理意义:
# - X_SHIFT_MM:
#   把GEANT4世界坐标的x原点平移到重建坐标参考原点。
# - Y_SIGN:
#   处理坐标轴方向差异（+1同向，-1反向）。
# - Y_SHIFT_MM:
#   把GEANT4坐标中的中心面平移到重建坐标参考面。
#
# 这些参数为什么存在:
# - GEANT4输出的是“世界坐标系”中的命中点/散射点坐标；
# - 重建算法使用的是“以针孔/旋转中心为参考”的计算坐标；
# - 两个坐标系的原点和轴向定义不同，必须先做配准。
#
# 当前默认值来源（与 geant4_simulation/config/pmma_1.yaml 对齐）:
# - phantom.center_x_mm = 60.0
# - phantom.center_y_mm = 50.0
# - phantom.center_z_mm = 0.0
# - 因此默认取 X_SHIFT_MM=-60，使 x 以 60 mm 为中心对齐；
# - 默认取 Y_SHIFT_MM=50，用于把 y 以 50 mm 为中心面对齐；
# - Y_SIGN=-1 来自当前重建代码使用的轴向约定（轴反向）。
#
# 维护建议:
# - 若GEANT4几何中心/摆位改变（如 PhantomContainer 平移变更），
#   需同步更新这里的参数；
# - 优先依据几何定义推导，不建议盲目手调。
X_SHIFT_MM = -60.0
Y_SIGN = -1.0
Y_SHIFT_MM = 50.0
