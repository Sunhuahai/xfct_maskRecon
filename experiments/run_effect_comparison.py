def _ensure_projection_subsamples() -> None:
    mask_45 = PROJECTION_FILES["mask_45"]
    mask_5 = output_path_for(mask_45, 5)
    mask_15 = output_path_for(mask_45, 15)
    if not mask_5.exists() or not mask_15.exists():
        subsample(mask_45, [5, 15])
    PROJECTION_FILES["mask_5"] = mask_5
    PROJECTION_FILES["mask_15"] = mask_15

    single_45 = PROJECTION_FILES["generated_single_45"]
    single_5 = output_path_for(single_45, 5)
    single_15 = output_path_for(single_45, 15)
    if single_45.exists() and (not single_5.exists() or not single_15.exists()):
        subsample(single_45, [5, 15])
    PROJECTION_FILES["generated_single_5"] = single_5
    PROJECTION_FILES["generated_single_15"] = single_15


def _validate_projection(projection: np.ndarray, spec: RunSpec) -> None:
    if projection.ndim != 3:
        raise ValueError(f"{spec.name}: projection must have [angle,z,x], got {projection.shape}.")
    if projection.shape[0] != spec.angle_count:
        raise ValueError(
            f"{spec.name}: expected {spec.angle_count} angles, got {projection.shape[0]}."
        )
    if tuple(projection.shape[1:]) != PROJECTION_HW:
        raise ValueError(
            f"{spec.name}: expected detector shape {PROJECTION_HW}, got {projection.shape[1:]}."
        )


def _load_projection(spec: RunSpec, output_dir: Path, args: argparse.Namespace) -> tuple[np.ndarray, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    projection_path = PROJECTION_FILES[spec.projection_key]
    projection = np.load(projection_path)
    _validate_projection(projection, spec)

    if spec.decode == "wiener":
        mask_spec = build_mask_spec(
            layout="grid3x3",
            pitch_mm=args.mask_pitch_mm,
            hole_diameter_mm=args.mask_hole_diameter_mm,
            rows=3,
            cols=3,
        )
        decode_cfg = MaskDecodeConfig(
            detector_pixel_size_mm=args.detector_pixel_size_mm,
            detector_to_mask_mm=args.detector_to_mask_mm,
            center_to_mask_mm=args.center_to_mask_mm,
            wiener_reg=args.wiener_reg,
            normalize_kernel=True,
            clip_nonnegative=True,
        )
        projection, kernel = wiener_decode_projection(
            projection,
            hole_centers_xz_mm=mask_spec.hole_centers,
            config=decode_cfg,
        )
        decoded_path = output_dir / "decoded_projection.npy"
        np.save(decoded_path, projection)
        np.save(output_dir / "wiener_kernel.npy", kernel)
        projection_path = decoded_path

    if args.poisson_seed is not None:
        rng = np.random.default_rng(int(args.poisson_seed))
        projection = rng.poisson(np.maximum(projection, 0.0)).astype(np.float64)
        noisy_path = output_dir / "poisson_projection.npy"
        np.save(noisy_path, projection)
        projection_path = noisy_path

    if args.match_total_counts:
        ref = np.load(PROJECTION_FILES["traditional_5"])
        ref_sum = float(np.sum(ref))
        proj_sum = float(np.sum(projection))
        if proj_sum > 0.0:
            projection = projection * (ref_sum / proj_sum)
            scaled_path = output_dir / "count_matched_projection.npy"
            np.save(scaled_path, projection)
            projection_path = scaled_path

    return projection, projection_path


def _common_config(
    *,
    projection_path: Path,
    system_matrix_path: Path,
    angle_count: int,
    num_iterations: int,
) -> CommonConfig:
    return CommonConfig(
        num_iterations=int(num_iterations),
        angle_count=int(angle_count),
        background_offset=0.0,
        recon_size=RECON_SHAPE,
        slice_index=20,
        pad_x=PAD_X,
        proj_path=str(projection_path),
        cij_path=str(system_matrix_path),
    )


def _system_matrix_path(spec: RunSpec, args: argparse.Namespace) -> Path:
    if spec.system_matrix_kind == "single":
        return SYSTEM_MATRIX_FILES[int(spec.angle_count)]
    if spec.system_matrix_kind != "mask":
        raise ValueError(f"Unsupported system_matrix_kind: {spec.system_matrix_kind}")

    if args.mask_system_matrix:
        path = Path(args.mask_system_matrix)
    else:
        path = (
            PROJECT_ROOT
            / "data/system_matrix"
            / (
                "cij_5_3d_mod30_cmask_grid3x3_n9_p6_d1d25_"
                "lim0d5_xy60_z40_att_pmma.npz"
            )
        )
    if not path.exists():
        raise FileNotFoundError(
            f"Mask system matrix is required for {spec.name}: {path}. "
            "Generate it with scripts/build_mask_system_matrix.py "
            "--angle-indices 0,9,18,27,36."
        )
    return path


def _run_method(
    *,
    method: str,
    spec: RunSpec,
    projection: np.ndarray,
    projection_path: Path,
    output_dir: Path,
    args: argparse.Namespace,
) -> dict[str, str | float]:
    common = _common_config(
        projection_path=projection_path,
        system_matrix_path=_system_matrix_path(spec, args),
        angle_count=spec.angle_count,
        num_iterations=args.num_iterations,
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    if method == "em_tv":
        result = run_em_tv_and_save_figure(
            projection=projection,
            common=common,
            image_output_path=output_dir / "reconstruction.png",
            volume_output_path=output_dir / "reconstruction.npy",
            results_output_path=output_dir / "reconstruction_results.npz",
            use_tv=True,
            tv_beta=args.tv_beta,
            tv_delta=1.0e-6,
            tv_steps=args.tv_steps,
            tv_warmup=args.tv_warmup,
            tv_alpha_mode="auto",
            lambda_l1=args.lambda_l1,
            l1_step=args.l1_step,
            slice_index=20,
            roi_layout="simulation",
            roi_reference_index=5,
            roi_reference_value_mgml=3.0,
            post_recon_scaling=True,
            name=f"{spec.name}_{method}",
        )
    elif method == "pseudo_mbir":
        pseudo_cfg = {
            "target_angle_count": 15 if spec.angle_count <= 15 else spec.angle_count,
            "coarse_iterations": "auto",
            "mbir_iterations": "remaining",
            "completion_method": "depth_warp",
            "blend_multiplicative": 0.5,
            "residual_strength": 0.25,
            "uncertainty_floor": 1.0,
            "pseudo_weight_scale": 1.0,
            "pseudo_weight_percentile": 95.0,
            "pseudo_mu": 0.2,
            "pseudo_step": 0.5,
            "lambda_l1": 0.0,
            "lambda_flux": 0.0,
        }
        if spec.angle_count <= 15:
            pseudo_cfg["target_cij_path"] = str(SYSTEM_MATRIX_FILES[15])
        result = run_reconstruction_and_save_figure(
            projection=projection,
            common=common,
            image_output_path=output_dir / "reconstruction.png",
            volume_output_path=output_dir / "reconstruction.npy",
            results_output_path=output_dir / "reconstruction_results.npz",
            use_tv=True,
            tv_beta=args.tv_beta,
            tv_delta=1.0e-6,
            tv_steps=args.tv_steps,
            tv_warmup=args.tv_warmup,
            tv_alpha_mode="auto",
            slice_index=20,
            roi_layout="simulation",
            roi_reference_index=5,
            roi_reference_value_mgml=3.0,
            post_recon_scaling=True,
            pseudo_mbir_cfg=pseudo_cfg,
        )
    else:
        raise ValueError(f"Unsupported method: {method}")

    roi = result["roi"]
    summary = result["summary"]
    dl_valid = bool(roi.get("detection_limit_valid", False))
    return {
        "run": spec.name,
        "method": method,
        "decode": spec.decode,
        "angle_count": float(spec.angle_count),
        "projection_sum": float(np.sum(projection)),
        "projection_max": float(np.max(projection)),
        "detection_limit_mgml": float(roi["DL"]),
        "detection_limit_valid": dl_valid,
        "detection_limit_invalid": bool(not dl_valid),
        "detection_limit_invalid_reason": str(
            roi.get("detection_limit_invalid_reason", "missing quality check")
        ),
        "roi_r_squared": float(roi["r_squared"]),
        "cnr_slope": float(roi.get("cnr_slope", np.nan)),
        "cnr_intercept": float(roi.get("cnr_intercept", np.nan)),
        "cnr_monotonic": bool(roi.get("cnr_monotonic", False)),
        "background_mean": float(roi.get("background_mean", np.nan)),
        "background_std": float(roi.get("background_std", np.nan)),
        "final_nll": float(summary["final_nll"]),
        "final_rel": float(summary["final_rel"]),
        "projection_path": str(projection_path),
        "system_matrix_path": str(common.cij_path),
        "reconstruction_path": str(output_dir / "reconstruction.png"),
        "volume_path": str(output_dir / "reconstruction.npy"),
        "note": spec.note,
    }


def _write_summary(rows: list[dict[str, str | float]], output_root: Path) -> None:
    if not rows:
        return
    csv_path = output_root / "effect_comparison.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    md_path = output_root / "effect_comparison.md"
    lines = [
        "# Mask Reconstruction Effect Comparison",
        "",
        "| run | method | angles | decode | DL status | R2 | counts | note |",
        "| --- | --- | ---: | --- | --- | ---: | ---: | --- |",
    ]
    for row in rows:
        if bool(row.get("detection_limit_valid", False)):
            dl_status = f"valid {float(row['detection_limit_mgml']):.4f} mg/ml"
        else:
            dl_status = (
                f"invalid; raw={float(row['detection_limit_mgml']):.4f}; "
                f"{row.get('detection_limit_invalid_reason', 'failed quality check')}"
            )
        lines.append(
            "| {run} | {method} | {angle_count:.0f} | {decode} | "
            "{dl_status} | {roi_r_squared:.4f} | "
            "{projection_sum:.4e} | {note} |".format(dl_status=dl_status, **row)
        )
    lines.append("")
    lines.append(f"CSV: `{csv_path}`")
    md_path.write_text("\n".join(lines), encoding="utf-8")


def _save_panel(rows: list[dict[str, str | float]], output_root: Path) -> None:
    if not rows:
        return
    cols = min(3, len(rows))
    grid_rows = int(np.ceil(len(rows) / cols))
    fig, axes = plt.subplots(grid_rows, cols, figsize=(5.2 * cols, 4.8 * grid_rows))
    axes_arr = np.atleast_1d(axes).ravel()
    for axis, row in zip(axes_arr, rows):
        volume = np.load(str(row["volume_path"]))
        image = volume[20]
        im = axis.imshow(image, cmap="jet", origin="upper", vmin=0.0, vmax=3.0)
        dl_label = (
            f"DL={float(row['detection_limit_mgml']):.3f}"
            if bool(row.get("detection_limit_valid", False))
            else "DL invalid"
        )
        axis.set_title(
            f"{row['run']} / {row['method']}\n{dl_label}"
        )
        axis.set_xlabel("Y")
        axis.set_ylabel("X")
        fig.colorbar(im, ax=axis, fraction=0.046, pad=0.04)
    for axis in axes_arr[len(rows) :]:
        axis.axis("off")
    fig.tight_layout()
    fig.savefig(output_root / "reconstruction_panel.png", dpi=180)
    plt.close(fig)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run coded-mask baseline reconstruction and compare to 15/45-angle single-pinhole data."
    )
    parser.add_argument(
        "--runs",
        default="traditional_5,mask_5_naive,mask_5_wiener,mask_5_model,traditional_15,traditional_45",
        help="Comma-separated run keys.",
    )
    parser.add_argument(
        "--methods",
        default="em_tv",
        help="Comma-separated methods: em_tv,pseudo_mbir.",
    )
    parser.add_argument(
        "--output-root",
        default=str(PROJECT_ROOT / "results" / "effect_comparison"),
        help="Output directory.",
    )
    parser.add_argument("--num-iterations", type=int, default=35)
    parser.add_argument("--quick", action="store_true", help="Use 3 iterations for smoke tests.")
    parser.add_argument("--tv-beta", type=float, default=1.0)
    parser.add_argument("--tv-steps", type=int, default=5)
    parser.add_argument("--tv-warmup", type=int, default=10)
    parser.add_argument("--lambda-l1", type=float, default=0.0)
    parser.add_argument("--l1-step", type=float, default=0.5)
    parser.add_argument("--poisson-seed", type=int, default=None)
    parser.add_argument(
        "--match-total-counts",
        action="store_true",
        help="Scale every input projection to the traditional 5-angle total counts.",
    )
    parser.add_argument("--mask-pitch-mm", type=float, default=6.0)
    parser.add_argument("--mask-hole-diameter-mm", type=float, default=1.25)
    parser.add_argument(
        "--mask-system-matrix",
        default=None,
        help="Path to a matching multi-hole system matrix for mask_*_model runs.",
    )
    parser.add_argument("--detector-pixel-size-mm", type=float, default=0.25)
    parser.add_argument("--detector-to-mask-mm", type=float, default=30.0)
    parser.add_argument("--center-to-mask-mm", type=float, default=50.0)
    parser.add_argument("--wiener-reg", type=float, default=0.03)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.quick:
        args.num_iterations = 3
        args.tv_warmup = min(args.tv_warmup, 2)

    _ensure_projection_subsamples()
    run_keys = [item.strip() for item in args.runs.split(",") if item.strip()]
    methods = [item.strip() for item in args.methods.split(",") if item.strip()]
    output_root = Path(args.output_root)
    output_root.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, str | float]] = []
    for run_key in run_keys:
        if run_key not in RUN_SPECS:
            raise KeyError(f"Unknown run key {run_key!r}. Available: {sorted(RUN_SPECS)}")
        spec = RUN_SPECS[run_key]
        for method in methods:
            run_output = output_root / f"{spec.name}_{method}"
            projection, projection_path = _load_projection(spec, run_output, args)
            row = _run_method(
                method=method,
                spec=spec,
                projection=projection,
                projection_path=projection_path,
                output_dir=run_output,
                args=args,
            )
            rows.append(row)
            dl_status = (
                f"DL={row['detection_limit_mgml']:.4f}"
                if bool(row.get("detection_limit_valid", False))
                else f"DL invalid ({row['detection_limit_invalid_reason']})"
            )
            print(
                f"{spec.name}/{method}: "
                f"{dl_status}, "
                f"R2={row['roi_r_squared']:.4f}, "
                f"counts={row['projection_sum']:.4e}"
            )

    _write_summary(rows, output_root)
    _save_panel(rows, output_root)
    print(f"Summary: {output_root / 'effect_comparison.csv'}")
    print(f"Panel: {output_root / 'reconstruction_panel.png'}")


if __name__ == "__main__":
    main()
